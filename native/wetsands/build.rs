//! Generates `source.rs`: the values the Source SDK's headers name, read
//! from native/vendor/source-sdk-2013 (build/headers.rs), a module a header.

#[path = "build/headers.rs"]
mod headers;

use std::fmt::Write;
use std::path::Path;

/// Rust module name -> header, under the SDK's root.
const HEADERS: &[(&str, &str)] = &[
    ("nav", "src/game/server/nav.h"),
    ("nav_pathfind", "src/game/server/nav_pathfind.h"),
    ("tf_nav_area", "src/game/server/tf/nav_mesh/tf_nav_area.h"),
];

fn main() {
    let sdk = Path::new(env!("CARGO_MANIFEST_DIR")).join("../vendor/source-sdk-2013");
    let mut out = String::from("// Generated by build.rs from the Source SDK 2013's headers; do not edit.\n");
    for (module, header) in HEADERS {
        let path = sdk.join(header);
        println!("cargo:rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let constants = headers::constants(&text).unwrap_or_else(|e| panic!("{header}: {e}"));
        writeln!(out, "/// {header}\n#[allow(non_upper_case_globals, dead_code)]\npub mod {module} {{").unwrap();
        out.push_str(&headers::rust(&constants));
        out.push_str("}\n");
    }
    println!("cargo:rerun-if-changed=build/headers.rs");
    let target = Path::new(&std::env::var("OUT_DIR").unwrap()).join("source.rs");
    std::fs::write(target, out).unwrap();
}
