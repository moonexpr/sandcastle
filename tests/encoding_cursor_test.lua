-- foundation.encoding.cursor: a position in text that parsers move along.
local T = dofile("tests/harness.lua")
local Cursor = T.require("foundation.encoding.cursor")

T.test("a literal is taken where it stands, and nothing moves when it does not", function()
	local c = Cursor.New("hello world")
	T.eq(c:Literal("world"), nil, "not here")
	T.eq(c:Position(), 1, "unmoved")
	T.eq(c:Literal("hello"), "hello", "taken")
	T.eq(c:Position(), 6, "moved past it")
end)

T.test("a literal may ignore case, and gives back the text as written", function()
	local c = Cursor.New("SELECT x")
	T.eq(c:Literal("select", true), "SELECT", "as written")
end)

T.test("a literal's magic characters are plain", function()
	local c = Cursor.New("a.b%c")
	T.eq(c:Literal("a.b%c"), "a.b%c", "dot and percent")
	T.eq(Cursor.New("axb"):Literal("a.b"), nil, "a dot is not any character")
end)

T.test("a pattern is matched where the cursor stands", function()
	local c = Cursor.New("123abc")
	T.eq(c:Pattern("%a+"), nil, "letters are not at the start")
	T.eq(c:Pattern("%d+"), "123", "digits")
	T.eq(c:Peek("%a+"), "abc", "peeked")
	T.eq(c:Position(), 4, "peeking does not move")
	T.eq(c:Pattern("%a+"), "abc", "letters")
	T.eq(c:AtEnd(), true, "the end")
end)

T.test("a pattern's captures come back, the cursor past the whole match", function()
	local c = Cursor.New("x=12;")
	local key, value = c:Pattern("(%a+)=(%d+)")
	T.eq(key, "x", "first capture")
	T.eq(value, "12", "second")
	T.eq(c:Literal(";"), ";", "past the match")
end)

T.test("whitespace is skipped", function()
	local c = Cursor.New("  \t\nword")
	c:Whitespace()
	T.eq(c:Literal("word"), "word", "after the space")
	T.eq(Cursor.New("word"):Whitespace(), nil, "none to skip")
end)

T.test("a saved position can be restored to backtrack, or committed", function()
	local c = Cursor.New("abc")
	c:Save()
	c:Literal("ab")
	c:Restore()
	T.eq(c:Position(), 1, "back")
	c:Save()
	c:Literal("ab")
	c:Commit()
	T.eq(c:Position(), 3, "kept")
	T.eq(c:Rest(), "c", "what is left")
end)

T.finish()
