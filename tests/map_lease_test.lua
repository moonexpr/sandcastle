-- foundation.map.lease: keys held by one holder each, for a time.
local T = dofile("tests/harness.lua")
local Lease = T.require("foundation.map.lease")

T.test("a lease holds a key for its holder until it expires", function()
	local leases = Lease.New()
	T.eq(leases:Holder("k", 0), nil, "free at first")
	T.eq(leases:Take("k", "a", 0, 10), true, "a takes it")
	T.eq(leases:Holder("k", 9), "a", "held")
	T.eq(leases:Holder("k", 10), nil, "expired at its end")
end)

T.test("only its holder may renew a held key, until it expires", function()
	local leases = Lease.New()
	leases:Take("k", "a", 0, 10)
	T.eq(leases:FreeFor("k", "b", 5), false, "not for b")
	T.eq(leases:FreeFor("k", "a", 5), true, "a's own")
	T.eq(leases:Take("k", "b", 5, 10), false, "b is refused")
	T.eq(leases:Take("k", "a", 5, 10), true, "a renews")
	T.eq(leases:Holder("k", 12), "a", "renewed past the first term")
	T.eq(leases:Take("k", "b", 15, 10), true, "b once it expired")
end)

T.test("a holder releases its own leases, never another's", function()
	local leases = Lease.New()
	leases:Take("k", "a", 0, 10)
	leases:Take("j", "a", 0, 10)
	leases:Take("m", "b", 0, 10)
	leases:Release("m", "a")
	T.eq(leases:Holder("m", 1), "b", "b's stays")
	leases:Release("k", "a")
	T.eq(leases:Holder("k", 1), nil, "released")
	leases:ReleaseAll("a")
	T.eq(leases:Holder("j", 1), nil, "all of a's")
	T.eq(leases:Holder("m", 1), "b", "b's untouched")
end)

T.finish()
