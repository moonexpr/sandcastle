-- foundation.economy: every player and team NPC holds money, opened at the
-- starting amount; earning adds to it and spending can never overdraw it.
local T = dofile("tests/harness.lua")
local Economy = T.require("foundation.economy")
local Refusal = T.require("foundation.refusal")

T.test("everyone starts with the starting money", function()
	T.defined(Economy.STARTING_MONEY, "Economy.STARTING_MONEY")
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	T.eq(Economy.Balance(ledger, "scout"), Economy.STARTING_MONEY)
end)

T.test("opening an account twice keeps its money", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	Economy.Earn(ledger, "scout", 500)
	Economy.Open(ledger, "scout")
	T.eq(Economy.Balance(ledger, "scout"), Economy.STARTING_MONEY + 500, "a respawn or team change is not a new account")
end)

T.test("earning and spending move the balance", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "heavy")
	Economy.Earn(ledger, "heavy", 300)
	Economy.Spend(ledger, "heavy", 1000)
	T.eq(Economy.Balance(ledger, "heavy"), Economy.STARTING_MONEY + 300 - 1000)
end)

T.test("spending more than the balance is refused and leaves it alone", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "spy")
	local ok, err = pcall(Economy.Spend, ledger, "spy", Economy.STARTING_MONEY + 1)
	T.eq(ok, false)
	T.eq(err.kind, Economy.INSUFFICIENT_FUNDS, "a named refusal")
	T.eq(Economy.Balance(ledger, "spy"), Economy.STARTING_MONEY)
	T.eq(Economy.CanAfford(ledger, "spy", Economy.STARTING_MONEY), true)
	T.eq(Economy.CanAfford(ledger, "spy", Economy.STARTING_MONEY + 1), false)
end)

T.test("an overdraw is the player's refusal, and says what was wanted and held", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "spy")
	local _, err = pcall(Economy.Spend, ledger, "spy", Economy.STARTING_MONEY + 1)
	T.eq(Refusal.Is(err, Economy.PLAYER), true)
	T.eq(Refusal.Message(err), "insufficient funds: 2001 wanted, 2000 held")
end)

T.test("spending the whole balance is allowed", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "spy")
	Economy.Spend(ledger, "spy", Economy.STARTING_MONEY)
	T.eq(Economy.Balance(ledger, "spy"), 0)
end)

T.test("amounts are whole, non-negative dollars", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "pyro")
	T.eq(pcall(Economy.Earn, ledger, "pyro", -5), false, "a negative earning")
	T.eq(pcall(Economy.Spend, ledger, "pyro", 1.5), false, "a fraction")
	T.eq(Economy.Balance(ledger, "pyro"), Economy.STARTING_MONEY)
end)

T.test("a bad amount and a missing account are our bugs, not refusals", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "pyro")
	local _, fraction = pcall(Economy.Spend, ledger, "pyro", 1.5)
	T.eq(Refusal.Is(fraction, Economy.PLAYER), false, "a fraction")
	local _, nobody = pcall(Economy.Spend, ledger, "nobody", 1)
	T.eq(Refusal.Is(nobody, Economy.PLAYER), false, "no account")
end)

T.test("an account must be open to use", function()
	local ledger = Economy.New()
	T.eq(pcall(Economy.Balance, ledger, "nobody"), false)
	T.eq(pcall(Economy.Earn, ledger, "nobody", 1), false)
end)

T.test("closing an account forgets it, and reopening starts fresh", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "medic")
	Economy.Spend(ledger, "medic", 2000)
	Economy.Close(ledger, "medic")
	T.eq(Economy.Has(ledger, "medic"), false)
	Economy.Open(ledger, "medic")
	T.eq(Economy.Balance(ledger, "medic"), Economy.STARTING_MONEY)
end)

T.test("a ledger made before a rerun of the economy still refuses an overdraw the new code recognises", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "spy")
	package.loaded["foundation.economy"] = nil
	local Rerun = T.require("foundation.economy")
	local ok, err = pcall(Rerun.Spend, ledger, "spy", Rerun.STARTING_MONEY + 1)
	T.eq(ok, false)
	T.eq(Refusal.Is(err, Rerun.PLAYER), true, "recognised after the rerun")
	T.eq(Rerun.Balance(ledger, "spy"), Rerun.STARTING_MONEY, "and the balance is untouched")
end)

T.test("a transfer moves money from one account to another", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	Economy.Open(ledger, "medic")
	Economy.Transfer(ledger, "scout", "medic", 50)
	T.eq(Economy.Balance(ledger, "scout"), Economy.STARTING_MONEY - 50)
	T.eq(Economy.Balance(ledger, "medic"), Economy.STARTING_MONEY + 50)
end)

T.test("a transfer the giver cannot afford is refused and moves nothing", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	Economy.Open(ledger, "medic")
	local ok, err = pcall(Economy.Transfer, ledger, "scout", "medic", Economy.STARTING_MONEY + 1)
	T.eq(ok, false)
	T.eq(err.kind, Economy.INSUFFICIENT_FUNDS)
	T.eq(Economy.Balance(ledger, "scout"), Economy.STARTING_MONEY)
	T.eq(Economy.Balance(ledger, "medic"), Economy.STARTING_MONEY)
end)

T.test("giving to yourself or giving nothing is the player's refusal", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	Economy.Open(ledger, "medic")
	local _, self = pcall(Economy.Transfer, ledger, "scout", "scout", 10)
	T.eq(Refusal.Is(self, Economy.PLAYER), true)
	T.eq(self.kind, Economy.SELF_TRANSFER)
	local _, nothing = pcall(Economy.Transfer, ledger, "scout", "medic", 0)
	T.eq(Refusal.Is(nothing, Economy.PLAYER), true)
	T.eq(nothing.kind, Economy.NO_AMOUNT)
	T.eq(Economy.Balance(ledger, "scout"), Economy.STARTING_MONEY)
end)

T.test("a transfer to an account that is not open moves nothing", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	T.eq(pcall(Economy.Transfer, ledger, "scout", "nobody", 10), false)
	T.eq(Economy.Balance(ledger, "scout"), Economy.STARTING_MONEY, "the giver keeps it")
end)

T.test("money reads as dollars with thousands separated", function()
	T.eq(Economy.Format(0), "$0")
	T.eq(Economy.Format(950), "$950")
	T.eq(Economy.Format(2000), "$2,000")
	T.eq(Economy.Format(1234567), "$1,234,567")
end)

T.test("a debt reads with the minus before the dollar sign", function()
	T.eq(Economy.Format(-5), "-$5")
	T.eq(Economy.Format(-123), "-$123")
	T.eq(Economy.Format(-1234), "-$1,234")
end)

T.test("credit: none unless deficit spending is on or the map plays like Sandbox", function()
	T.eq(Economy.Floor(false, false), Economy.NO_CREDIT)
	T.eq(Economy.Floor(true, false), Economy.BALANCE_MIN, "mp_economy_credit_enabled")
	T.eq(Economy.Floor(false, true), Economy.BALANCE_MIN, "Sandbox mode")
	T.eq(Economy.BALANCE_MIN, -2 ^ 31, "the lowest ws_money, a signed 32-bit NW2 int, can carry")
end)

T.test("spending on credit goes below zero, down to the floor and no further", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	Economy.SpendWithCredit(ledger, "scout", Economy.STARTING_MONEY + 500, Economy.BALANCE_MIN)
	T.eq(Economy.Balance(ledger, "scout"), -500)
	local ok, err = pcall(Economy.SpendWithCredit, ledger, "scout", 1, -500)
	T.eq(ok, false)
	T.eq(err.kind, Economy.INSUFFICIENT_FUNDS)
	T.eq(Economy.Balance(ledger, "scout"), -500, "untouched")
end)

T.test("spending with no credit is spending", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	local ok = pcall(Economy.SpendWithCredit, ledger, "scout", Economy.STARTING_MONEY + 1, Economy.NO_CREDIT)
	T.eq(ok, false)
end)

T.test("a floor above zero, or not whole, is our bug", function()
	local ledger = Economy.New()
	Economy.Open(ledger, "scout")
	local _, above = pcall(Economy.SpendWithCredit, ledger, "scout", 1, 10)
	T.eq(Refusal.Is(above, Economy.PLAYER), false)
	local _, fraction = pcall(Economy.SpendWithCredit, ledger, "scout", 1, -0.5)
	T.eq(Refusal.Is(fraction, Economy.PLAYER), false)
end)

T.test("Affords answers as SpendWithCredit would", function()
	T.eq(Economy.Affords(10, 10, Economy.NO_CREDIT), true)
	T.eq(Economy.Affords(9, 10, Economy.NO_CREDIT), false)
	T.eq(Economy.Affords(-100, 10, Economy.BALANCE_MIN), true)
end)

T.test("with the economy off, spending and giving are refused as the player's", function()
	T.eq(Economy.PLAYER[Economy.ECONOMY_OFF], true)
end)

T.finish()
