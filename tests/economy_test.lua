-- foundation.economy: every player and team NPC holds money, opened at the
-- starting amount; earning adds to it and spending can never overdraw it.
local T = dofile("tests/harness.lua")
local Economy = T.require("foundation.economy")

T.test("everyone starts with the starting money", function()
	T.defined(Economy.STARTING_MONEY, "Economy.STARTING_MONEY")
	local bank = Economy.New()
	bank:Open("scout")
	T.eq(bank:Balance("scout"), Economy.STARTING_MONEY)
end)

T.test("opening an account twice keeps its money", function()
	local bank = Economy.New()
	bank:Open("scout")
	bank:Earn("scout", 500)
	bank:Open("scout")
	T.eq(bank:Balance("scout"), Economy.STARTING_MONEY + 500, "a respawn or team change is not a new account")
end)

T.test("earning and spending move the balance", function()
	local bank = Economy.New()
	bank:Open("heavy")
	bank:Earn("heavy", 300)
	bank:Spend("heavy", 1000)
	T.eq(bank:Balance("heavy"), Economy.STARTING_MONEY + 300 - 1000)
end)

T.test("spending more than the balance is refused and leaves it alone", function()
	local bank = Economy.New()
	bank:Open("spy")
	local ok, err = pcall(bank.Spend, bank, "spy", Economy.STARTING_MONEY + 1)
	T.eq(ok, false)
	T.eq(getmetatable(err), Economy.InsufficientFunds, "a named refusal")
	T.eq(bank:Balance("spy"), Economy.STARTING_MONEY)
	T.eq(bank:CanAfford("spy", Economy.STARTING_MONEY), true)
	T.eq(bank:CanAfford("spy", Economy.STARTING_MONEY + 1), false)
end)

T.test("spending the whole balance is allowed", function()
	local bank = Economy.New()
	bank:Open("spy")
	bank:Spend("spy", Economy.STARTING_MONEY)
	T.eq(bank:Balance("spy"), 0)
end)

T.test("amounts are whole, non-negative dollars", function()
	local bank = Economy.New()
	bank:Open("pyro")
	T.eq(pcall(bank.Earn, bank, "pyro", -5), false, "a negative earning")
	T.eq(pcall(bank.Spend, bank, "pyro", 1.5), false, "a fraction")
	T.eq(bank:Balance("pyro"), Economy.STARTING_MONEY)
end)

T.test("an account must be open to use", function()
	local bank = Economy.New()
	T.eq(pcall(bank.Balance, bank, "nobody"), false)
	T.eq(pcall(bank.Earn, bank, "nobody", 1), false)
end)

T.test("closing an account forgets it, and reopening starts fresh", function()
	local bank = Economy.New()
	bank:Open("medic")
	bank:Spend("medic", 2000)
	bank:Close("medic")
	T.eq(bank:Has("medic"), false)
	bank:Open("medic")
	T.eq(bank:Balance("medic"), Economy.STARTING_MONEY)
end)

T.test("money reads as dollars with thousands separated", function()
	T.eq(Economy.Format(0), "$0")
	T.eq(Economy.Format(950), "$950")
	T.eq(Economy.Format(2000), "$2,000")
	T.eq(Economy.Format(1234567), "$1,234,567")
end)

T.finish()
