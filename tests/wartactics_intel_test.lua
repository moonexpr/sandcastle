-- wartactics.intel: what a team knows of the enemy, by room
-- (docs/special-missions-plan.md §2.2): only what its soldiers saw and
-- suffered, and when. How strongly a room is held, how often the enemy
-- passes through it, and where it keeps its support.
local T = dofile("tests/harness.lua")
local Intel = wartactics.intel

T.test("the tuning is defined", function()
	T.defined(Intel.GUARD_MEMORY, "GUARD_MEMORY")
	T.defined(Intel.TRAFFIC_MEMORY, "TRAFFIC_MEMORY")
	T.defined(Intel.SUPPORT_MEMORY, "SUPPORT_MEMORY")
	T.defined(Intel.LOSS_WEIGHT, "LOSS_WEIGHT")
	T.defined(Intel.WEIGHTS[Intel.TURRET], "a turret's weight")
	T.eq(Intel.WEIGHTS[Intel.TURRET] > Intel.WEIGHTS[Intel.SOLDIER], true, "a turret holds a room more than a soldier")
end)

T.test("an enemy seen holds its room a while, then is forgotten", function()
	local intel = Intel.New()
	intel:Sight(3, Intel.SOLDIER, "e1", 0)
	T.eq(intel:Guarded(3, 1), Intel.WEIGHTS[Intel.SOLDIER])
	T.eq(intel:Guarded(4, 1), 0, "another room")
	T.eq(intel:Guarded(3, Intel.GUARD_MEMORY + 1), 0, "forgotten")
end)

T.test("an enemy counts where it was seen last, once", function()
	local intel = Intel.New()
	intel:Sight(3, Intel.SOLDIER, "e1", 0)
	intel:Sight(3, Intel.SOLDIER, "e1", 1)
	T.eq(intel:Guarded(3, 1), Intel.WEIGHTS[Intel.SOLDIER], "seen twice, one enemy")
	intel:Sight(4, Intel.SOLDIER, "e1", 2)
	T.eq(intel:Guarded(3, 2), 0, "it moved on")
	T.eq(intel:Guarded(4, 2), Intel.WEIGHTS[Intel.SOLDIER])
end)

T.test("a turret holds a room more than a soldier", function()
	local intel = Intel.New()
	intel:Sight(3, Intel.TURRET, "t1", 0)
	intel:Sight(4, Intel.SOLDIER, "e1", 0)
	T.eq(intel:Guarded(3, 1) > intel:Guarded(4, 1), true)
end)

T.test("our losses in a room count it held, a while", function()
	local intel = Intel.New()
	intel:Loss(5, 0)
	intel:Loss(5, 1)
	T.eq(intel:Guarded(5, 2), 2 * Intel.LOSS_WEIGHT)
	T.eq(intel:Guarded(5, Intel.GUARD_MEMORY + 2), 0)
end)

T.test("an enemy gone (killed, destroyed) holds nothing", function()
	local intel = Intel.New()
	intel:Sight(3, Intel.TURRET, "t1", 0)
	intel:Gone("t1")
	T.eq(intel:Guarded(3, 1), 0)
	T.eq(#intel:SupportBases(1), 0)
end)

T.test("traffic: the enemies that came into a room lately, each arrival once", function()
	local intel = Intel.New()
	intel:Sight(3, Intel.SOLDIER, "e1", 0)
	intel:Sight(3, Intel.SOLDIER, "e1", 1)
	intel:Sight(3, Intel.SOLDIER, "e2", 2)
	T.eq(intel:Traffic(3, 3), 2, "two came, the first seen twice")
	intel:Sight(4, Intel.SOLDIER, "e1", 4)
	intel:Sight(3, Intel.SOLDIER, "e1", 5)
	T.eq(intel:Traffic(3, 6), 3, "it came back: another arrival")
	T.eq(intel:Traffic(3, 5 + Intel.TRAFFIC_MEMORY + 1), 0, "forgotten")
end)

T.test("support bases: rooms where enemy support stands, strongest first, longer remembered", function()
	local intel = Intel.New()
	intel:Sight(7, Intel.MEDIC, "m1", 0)
	intel:Sight(8, Intel.TURRET, "t1", 0)
	intel:Sight(8, Intel.DISPENSER, "d1", 0)
	intel:Sight(9, Intel.SOLDIER, "e1", 0)
	local bases = intel:SupportBases(1)
	T.eq(#bases, 2, "soldiers alone make no base")
	T.eq(bases[1].room, 8, "the turret and dispenser first")
	T.eq(bases[2].room, 7)
	T.eq(bases[1].strength, Intel.WEIGHTS[Intel.TURRET] + Intel.WEIGHTS[Intel.DISPENSER])
	T.eq(#intel:SupportBases(Intel.GUARD_MEMORY + 1), 2, "still remembered past a soldier's memory")
	T.eq(#intel:SupportBases(Intel.SUPPORT_MEMORY + 1), 0, "forgotten in time")
	T.eq(Intel.SUPPORT_MEMORY > Intel.GUARD_MEMORY, true)
end)

T.test("old arrivals and losses are let go, so a long round keeps short lists", function()
	local intel = Intel.New()
	for t = 0, 99 do intel:Sight(3, Intel.SOLDIER, "e" .. t, t) end
	T.eq(intel:Traffic(3, 99), Intel.TRAFFIC_MEMORY + 1, "the last TRAFFIC_MEMORY seconds' worth")
	T.eq(#intel.arrivals[3], Intel.TRAFFIC_MEMORY + 1, "the rest let go")
end)

T.test("an unknown kind is our bug", function()
	T.eq(pcall(Intel.New().Sight, Intel.New(), 1, "dragon", "x", 0), false)
end)

T.finish()
