-- foundation.world.pairmap: values kept by an ordered pair of whole
-- numbers (a link's two nav area ids), looked up without building a key.
local T = dofile("tests/harness.lua")
local PairMap = world.pairmap

T.test("a value is kept by its ordered pair", function()
	local map = PairMap.New()
	T.eq(map:Get(3, 7), nil, "nothing yet")
	map:Set(3, 7, true)
	map:Set(7, 3, false)
	T.eq(map:Get(3, 7), true, "3 then 7")
	T.eq(map:Get(7, 3), false, "7 then 3 is another pair")
	T.eq(map:Get(3, 8), nil, "nor any other")
	T.eq(map:Size(), 2, "two pairs")
end)

T.test("setting nil removes a pair, and Clear removes them all", function()
	local map = PairMap.New()
	map:Set(0, 0, "a")
	map:Set(1, PairMap.MAX_KEY, "b")
	T.eq(map:Get(1, PairMap.MAX_KEY), "b", "the largest key")
	map:Set(0, 0, nil)
	T.eq(map:Get(0, 0), nil, "removed")
	T.eq(map:Size(), 1, "one left")
	map:Set(0, 0, nil)
	T.eq(map:Size(), 1, "removing what is not there changes nothing")
	map:Clear()
	T.eq(map:Get(1, PairMap.MAX_KEY), nil, "cleared")
	T.eq(map:Size(), 0, "empty")
end)

T.test("pairs that would share a key are told apart: no pair aliases another", function()
	local map = PairMap.New()
	map:Set(1, 0, "one-zero")
	map:Set(0, PairMap.MAX_KEY, "zero-max")
	T.eq(map:Get(1, 0), "one-zero", "kept")
	T.eq(map:Get(0, PairMap.MAX_KEY), "zero-max", "kept apart")
end)

T.test("a key is a whole number from 0 to MAX_KEY", function()
	local map = PairMap.New()
	T.eq(pcall(map.Set, map, -1, 0, true), false, "negative")
	T.eq(pcall(map.Set, map, 1.5, 0, true), false, "a fraction")
	T.eq(pcall(map.Set, map, 0, PairMap.MAX_KEY + 1, true), false, "too large")
	T.eq(pcall(map.Set, map, "1", 0, true), false, "a string")
end)

T.finish()
