-- foundation.list.slots: whole-number slots handed out and taken back.
local T = dofile("tests/harness.lua")
local Slots = T.require("foundation.list.slots")

T.test("slots are handed out from one up, each to one holder", function()
	local pool = Slots.New()
	T.eq(pool:Size(), 0, "none in use")
	T.eq(pool:Alloc(), 1, "first")
	T.eq(pool:Alloc(), 2, "second")
	T.eq(pool:Size(), 2, "two in use")
	T.eq(pool:InUse(1), true, "the first is held")
	T.eq(pool:InUse(3), false, "a slot never handed out is not")
end)

T.test("a freed slot is handed out again before a new one", function()
	local pool = Slots.New()
	pool:Alloc()
	pool:Alloc()
	pool:Alloc()
	pool:Free(2)
	T.eq(pool:Size(), 2, "one fewer in use")
	T.eq(pool:InUse(2), false, "freed")
	T.eq(pool:Alloc(), 2, "reused")
	T.eq(pool:Alloc(), 4, "then a new one")
	T.eq(pool:High(), 4, "the most ever handed out")
end)

T.test("freeing a slot not in use is refused", function()
	local pool = Slots.New()
	T.eq(pcall(pool.Free, pool, 1), false, "never handed out")
	local slot = pool:Alloc()
	pool:Free(slot)
	T.eq(pcall(pool.Free, pool, slot), false, "freed twice")
end)

T.test("Clear takes every slot back", function()
	local pool = Slots.New()
	pool:Alloc()
	pool:Alloc()
	pool:Clear()
	T.eq(pool:Size(), 0, "none in use")
	T.eq(pool:Alloc(), 1, "handed out from one again")
end)

T.test("calling a pool hands out a slot", function()
	local pool = Slots.New()
	T.eq(pool(), 1, "a slot")
	T.eq(pool(), 2, "the next")
	T.eq(getmetatable(pool).__len(pool), pool:Size(), "__len is Size")
	T.eq(tostring(pool), "slots: 2 in use of 2", "it says what it holds")
end)

T.finish()
